#!/bin/bash
INPUTS=(
    # ========================================
    # DEGREE 0 — CONSTANT EQUATIONS
    # ========================================

    './computor "5 * X^0 = 5 * X^0"'
    './computor "7 * X^0 = 3 * X^0"'
    './computor "0 * X^0 = 0 * X^0"'
    './computor "9.5 * X^0 = 2.5 * X^0"'
    './computor "-4 * X^0 = -4 * X^0"'

    # ========================================
    # DEGREE 1 — LINEAR
    # ========================================

    './computor "5 * X^1 + 3 * X^0 = 0 * X^1 + 8 * X^0"'
    './computor "-7 * X^1 + 4 * X^0 = 3 * X^1 - 6 * X^0"'
    './computor "2.5 * X^1 - 7.5 * X^0 = 0 * X^1 + 5 * X^0"'
    './computor "0 * X^3 + 9 * X^1 + 4 * X^0 = 0 * X^3 + 2 * X^1 - 10 * X^0"'
    './computor "8 * X^1 + 0 * X^0 = 3 * X^1 + 0 * X^0"'

    # ========================================
    # DEGREE 2 — QUADRATIC
    # ========================================

    './computor "3 * X^2 + 5 * X^1 + 2 * X^0 = 0 * X^2 + 0 * X^1 + 0 * X^0"'
    './computor "4 * X^2 - 7 * X^1 + 3 * X^0 = 1 * X^2 + 2 * X^1 - 5 * X^0"'
    './computor "5 * X^2 + 0 * X^1 + 9 * X^0 = 0 * X^2 + 0 * X^1 + 1 * X^0"'
    './computor "-2 * X^2 + 6 * X^1 - 4 * X^0 = 3 * X^2 - 2 * X^1 + 5 * X^0"'
    './computor "0.5 * X^2 + 2.5 * X^1 + 1.5 * X^0 = 0.25 * X^2 - 1.5 * X^1 - 0.5 * X^0"'

    # ========================================
    # DEGREE 3 — CUBIC
    # ========================================

    './computor "4 * X^3 + 3 * X^2 + 2 * X^1 + 1 * X^0 = 0 * X^3 + 0 * X^2 + 0 * X^1 + 0 * X^0"'
    './computor "5 * X^3 - 4 * X^2 + 7 * X^1 - 2 * X^0 = 2 * X^3 + X^2 + 3 * X^1 + 6 * X^0"'
    './computor "-3 * X^3 + 8 * X^2 - 5 * X^1 + 9 * X^0 = 4 * X^3 - 2 * X^2 + X^1 - 3 * X^0"'
    './computor "2.5 * X^3 + 0 * X^2 - 7.5 * X^1 + 4 * X^0 = 1.5 * X^3 + 2 * X^2 + 2.5 * X^1 - 6 * X^0"'
    './computor "9 * X^3 + 0 * X^2 + 0 * X^1 + 5 * X^0 = 4 * X^3 + 0 * X^2 + 0 * X^1 + 2 * X^0"'

    # ========================================
    # DEGREE 4 — QUARTIC
    # ========================================

    './computor "2 * X^4 + 3 * X^3 + 4 * X^2 + 5 * X^1 + 6 * X^0 = 0 * X^4 + 0 * X^3 + 0 * X^2 + 0 * X^1 + 0 * X^0"'
    './computor "7 * X^4 - 2 * X^3 + 5 * X^2 - 8 * X^1 + 3 * X^0 = 2 * X^4 + X^3 - 4 * X^2 + 3 * X^1 - 6 * X^0"'
    './computor "-4 * X^4 + 6 * X^3 - 2 * X^2 + 9 * X^1 - 5 * X^0 = X^4 - 3 * X^3 + 7 * X^2 - 2 * X^1 + 8 * X^0"'
    './computor "1.5 * X^4 + 2.25 * X^3 - 3.5 * X^2 + 4.75 * X^1 - 0.5 * X^0 = 0.5 * X^4 - 1.25 * X^3 + 2.5 * X^2 - 3.75 * X^1 + 1.5 * X^0"'
    './computor "0 * X^4 + 5 * X^3 - 2 * X^2 + 7 * X^1 - 9 * X^0 = 0 * X^4 + 2 * X^3 + X^2 - 4 * X^1 + 3 * X^0"'

    # ========================================
    # DEGREE 5 — QUINTIC
    # ========================================

    './computor "3 * X^5 + 4 * X^4 + 5 * X^3 + 6 * X^2 + 7 * X^1 + 8 * X^0 = 0 * X^5 + 0 * X^4 + 0 * X^3 + 0 * X^2 + 0 * X^1 + 0 * X^0"'
    './computor "6 * X^5 - 3 * X^4 + 8 * X^3 - 2 * X^2 + 9 * X^1 - 4 * X^0 = 2 * X^5 + X^4 - 5 * X^3 + 4 * X^2 - 3 * X^1 + 7 * X^0"'
    './computor "-5 * X^5 + 7 * X^4 - 3 * X^3 + 9 * X^2 - 6 * X^1 + 2 * X^0 = 4 * X^5 - 2 * X^4 + 8 * X^3 - X^2 + 5 * X^1 - 9 * X^0"'
    './computor "0.5 * X^5 + 1.25 * X^4 - 2.75 * X^3 + 3.5 * X^2 - 4.125 * X^1 + 0.75 * X^0 = 0.25 * X^5 - 0.75 * X^4 + 1.25 * X^3 - 2 * X^2 + 1.875 * X^1 - 1.5 * X^0"'
    './computor "9 * X^5 + 0 * X^4 + 7 * X^3 + 0 * X^2 + 5 * X^1 + 0 * X^0 = 3 * X^5 + 0 * X^4 + 2 * X^3 + 0 * X^2 + X^1 + 0 * X^0"'

    # ========================================
    # DEGREE 6 — SEXTIC
    # ========================================

    './computor "2 * X^6 + 3 * X^5 + 4 * X^4 + 5 * X^3 + 6 * X^2 + 7 * X^1 + 8 * X^0 = 0 * X^6 + 0 * X^5 + 0 * X^4 + 0 * X^3 + 0 * X^2 + 0 * X^1 + 0 * X^0"'
    './computor "5 * X^6 - 4 * X^5 + 3 * X^4 - 2 * X^3 + X^2 - 7 * X^1 + 9 * X^0 = 2 * X^6 + 3 * X^5 - X^4 + 4 * X^3 - 5 * X^2 + 2 * X^1 - 6 * X^0"'
    './computor "-7 * X^6 + 2 * X^5 + 9 * X^4 - 3 * X^3 + 5 * X^2 - 8 * X^1 + 4 * X^0 = 3 * X^6 - 5 * X^5 + 2 * X^4 + 6 * X^3 - X^2 + 7 * X^1 - 9 * X^0"'
    './computor "0.25 * X^6 - 1.5 * X^5 + 2.75 * X^4 - 3.125 * X^3 + 4.5 * X^2 - 5.75 * X^1 + 6.25 * X^0 = 0.125 * X^6 + 0.5 * X^5 - 1.25 * X^4 + 2.375 * X^3 - 3.5 * X^2 + 4.25 * X^1 - 2.75 * X^0"'
    './computor "8 * X^6 + 0 * X^5 + 6 * X^4 + 0 * X^3 + 4 * X^2 + 0 * X^1 + 2 * X^0 = 3 * X^6 + 0 * X^5 + 5 * X^4 + 0 * X^3 + X^2 + 0 * X^1 + 7 * X^0"'

    # ========================================
    # DEGREE REDUCTION: 6 -> 5
    # ========================================

    './computor "5 * X^6 + 3 * X^5 + 2 * X^4 = 5 * X^6 + 0 * X^5 + 0 * X^4"'

    # ========================================
    # DEGREE REDUCTION: 6 -> 4
    # ========================================

    './computor "5 * X^6 + 3 * X^5 + 7 * X^4 + 2 * X^3 = 5 * X^6 + 3 * X^5 + 0 * X^4 + 0 * X^3"'

    # ========================================
    # DEGREE REDUCTION: 6 -> 3
    # ========================================

    './computor "5 * X^6 + 3 * X^5 + 7 * X^4 + 2 * X^3 = 5 * X^6 + 3 * X^5 + 7 * X^4 + 0 * X^3"'

    # ========================================
    # DEGREE REDUCTION: 6 -> 2
    # ========================================

    './computor "5 * X^6 + 3 * X^5 + 7 * X^4 + 2 * X^3 + 9 * X^2 = 5 * X^6 + 3 * X^5 + 7 * X^4 + 2 * X^3 + 0 * X^2"'

    # ========================================
    # DEGREE REDUCTION: 6 -> 1
    # ========================================

    './computor "5 * X^6 + 3 * X^5 + 7 * X^4 + 2 * X^3 + 9 * X^2 + 8 * X^1 + 4 * X^0 = 5 * X^6 + 3 * X^5 + 7 * X^4 + 2 * X^3 + 9 * X^2 + 3 * X^1 - 6 * X^0"'

    # ========================================
    # DEGREE REDUCTION: everything cancels
    # ========================================

    './computor "5 * X^6 + 3 * X^5 + 7 * X^4 + 2 * X^3 = 5 * X^6 + 3 * X^5 + 7 * X^4 + 2 * X^3"'

    # ========================================
    # Degree 0 contradiction
    # ========================================

    './computor "8 * X^6 + 5 * X^4 + 3 * X^2 + 9 * X^0 = 8 * X^6 + 5 * X^4 + 3 * X^2 + 4 * X^0"'
)


: > computor_test_results.txt

for cmd in "${INPUTS[@]}"; do
    echo "========================================" | tee -a computor_test_results.txt
    echo "$cmd" | tee -a computor_test_results.txt
    echo "========================================" | tee -a computor_test_results.txt
    eval "$cmd" 2>&1 | tee -a computor_test_results.txt
    echo | tee -a computor_test_results.txt
done

echo "Results saved to computor_test_results.txt"