#!/bin/bash
INPUTS=(
    # ========================================
    # Basic higher-degree cancellation
    # ========================================

    './computor "6 * X^3 + 11 * X^2 + 8 * X^1 + 4 * X^0 = 6 * X^3 + 11 * X^2 + 3 * X^1 - 6 * X^0"'
    './computor "9 * X^4 - 5 * X^3 + 7 * X^2 - 4 * X^1 + 8 * X^0 = 9 * X^4 - 5 * X^3 + 7 * X^2 + 5 * X^1 - 4 * X^0"'
    './computor "3 * X^5 + 8 * X^4 - 6 * X^2 + 9 * X^1 + 2 * X^0 = 3 * X^5 + 8 * X^4 - 6 * X^2 - 3 * X^1 + 10 * X^0"'

    # ========================================
    # Degree 6 / 7 / 8 cancellation
    # ========================================

    './computor "4 * X^6 + 7 * X^5 - 3 * X^4 + 9 * X^2 + 11 * X^1 - 5 * X^0 = 4 * X^6 + 7 * X^5 - 3 * X^4 + 9 * X^2 + 2 * X^1 + 6 * X^0"'
    './computor "8 * X^7 - 4 * X^6 + 3 * X^5 + 6 * X^3 - 7 * X^1 + 2 * X^0 = 8 * X^7 - 4 * X^6 + 3 * X^5 + 6 * X^3 + 5 * X^1 - 8 * X^0"'
    './computor "2 * X^8 + 5 * X^6 - 9 * X^4 + 3 * X^2 + 14 * X^1 - 7 * X^0 = 2 * X^8 + 5 * X^6 - 9 * X^4 + 3 * X^2 + 6 * X^1 + 1 * X^0"'

    # ========================================
    # Only X^1 and X^0 survive
    # ========================================

    './computor "5 * X^4 + 8 * X^3 + 2 * X^2 + 7 * X^1 + 9 * X^0 = 5 * X^4 + 8 * X^3 + 2 * X^2 + 3 * X^1 + 1 * X^0"'
    './computor "9 * X^6 - 4 * X^5 + 7 * X^3 + 12 * X^1 - 8 * X^0 = 9 * X^6 - 4 * X^5 + 7 * X^3 + 5 * X^1 + 6 * X^0"'
    './computor "7 * X^3 - 2 * X^2 + 4 * X^1 - 11 * X^0 = 7 * X^3 - 2 * X^2 - 6 * X^1 + 1 * X^0"'

    # ========================================
    # Missing intermediate powers
    # ========================================

    './computor "8 * X^6 + 5 * X^2 + 9 * X^0 = 8 * X^6 + 5 * X^2 + 4 * X^0"'
    './computor "3 * X^8 - 7 * X^5 + 12 * X^1 = 3 * X^8 - 7 * X^5 + 4 * X^1"'
    './computor "11 * X^9 + 6 * X^4 - 8 * X^1 - 3 * X^0 = 11 * X^9 + 6 * X^4 + 7 * X^1 + 2 * X^0"'

    # ========================================
    # Explicit zero terms
    # ========================================

    './computor "5 * X^5 + 0 * X^4 + 8 * X^3 + 0 * X^2 + 7 * X^1 + 3 * X^0 = 5 * X^5 + 0 * X^4 + 8 * X^3 + 0 * X^2 + 2 * X^1 - 7 * X^0"'
    './computor "0 * X^7 + 4 * X^6 + 0 * X^5 - 3 * X^3 + 0 * X^2 + 9 * X^1 + 5 * X^0 = 0 * X^7 + 4 * X^6 + 0 * X^5 - 3 * X^3 + 0 * X^2 + 1 * X^1 - 3 * X^0"'
    './computor "0 * X^8 + 0 * X^6 + 7 * X^4 + 0 * X^3 + 0 * X^2 - 6 * X^1 + 4 * X^0 = 0 * X^8 + 0 * X^6 + 7 * X^4 + 0 * X^3 + 0 * X^2 + 2 * X^1 - 8 * X^0"'

    # ========================================
    # Negative coefficients
    # ========================================

    './computor "-5 * X^6 + 7 * X^4 - 3 * X^2 - 9 * X^1 + 4 * X^0 = -5 * X^6 + 7 * X^4 - 3 * X^2 - 2 * X^1 - 6 * X^0"'
    './computor "-8 * X^5 - 4 * X^3 + 6 * X^2 + 11 * X^1 - 9 * X^0 = -8 * X^5 - 4 * X^3 + 6 * X^2 + 3 * X^1 + 5 * X^0"'
    './computor "6 * X^7 - 9 * X^6 - 4 * X^4 - 12 * X^1 + 7 * X^0 = 6 * X^7 - 9 * X^6 - 4 * X^4 + 5 * X^1 - 8 * X^0"'

    # ========================================
    # Decimal coefficients
    # ========================================

    './computor "5.5 * X^4 + 2.25 * X^3 - 7.5 * X^2 + 8.75 * X^1 + 1.5 * X^0 = 5.5 * X^4 + 2.25 * X^3 - 7.5 * X^2 + 3.25 * X^1 - 4.5 * X^0"'
    './computor "0.5 * X^6 - 3.75 * X^4 + 8.25 * X^2 - 6.5 * X^1 + 2.75 * X^0 = 0.5 * X^6 - 3.75 * X^4 + 8.25 * X^2 + 1.5 * X^1 - 5.25 * X^0"'
    './computor "-2.5 * X^5 + 4.75 * X^3 + 6.125 * X^1 - 3.75 * X^0 = -2.5 * X^5 + 4.75 * X^3 - 1.875 * X^1 + 2.25 * X^0"'

    # ========================================
    # Multiple higher-degree terms cancel
    # ========================================

    './computor "7 * X^6 + 5 * X^5 - 3 * X^4 + 8 * X^3 + 4 * X^2 + 9 * X^1 + 2 * X^0 = 7 * X^6 + 5 * X^5 - 3 * X^4 + 8 * X^3 + 4 * X^2 + 1 * X^1 - 6 * X^0"'
    './computor "3 * X^8 - 7 * X^7 + 5 * X^6 - 2 * X^5 + 9 * X^4 + 6 * X^2 - 11 * X^1 + 4 * X^0 = 3 * X^8 - 7 * X^7 + 5 * X^6 - 2 * X^5 + 9 * X^4 + 6 * X^2 + 8 * X^1 - 9 * X^0"'
    './computor "10 * X^9 - 4 * X^8 + 7 * X^7 - 6 * X^6 + 3 * X^5 + 8 * X^3 - 5 * X^2 + 13 * X^1 - 2 * X^0 = 10 * X^9 - 4 * X^8 + 7 * X^7 - 6 * X^6 + 3 * X^5 + 8 * X^3 - 5 * X^2 + 4 * X^1 + 7 * X^0"'

    # ========================================
    # X^1 coefficient becomes negative
    # ========================================

    './computor "4 * X^5 + 3 * X^3 + 2 * X^1 + 8 * X^0 = 4 * X^5 + 3 * X^3 + 9 * X^1 + 1 * X^0"'
    './computor "6 * X^7 - 2 * X^4 - 5 * X^2 - 3 * X^1 + 7 * X^0 = 6 * X^7 - 2 * X^4 - 5 * X^2 + 8 * X^1 - 4 * X^0"'

    # ========================================
    # X^1 coefficient becomes positive
    # ========================================

    './computor "9 * X^4 + 2 * X^2 - 8 * X^1 + 3 * X^0 = 9 * X^4 + 2 * X^2 - 13 * X^1 - 4 * X^0"'
    './computor "5 * X^6 - 7 * X^3 + 4 * X^1 - 9 * X^0 = 5 * X^6 - 7 * X^3 + 1 * X^1 + 6 * X^0"'

    # ========================================
    # Constant term cancels completely
    # ========================================

    './computor "7 * X^5 + 4 * X^3 + 9 * X^1 + 6 * X^0 = 7 * X^5 + 4 * X^3 + 2 * X^1 + 6 * X^0"'
    './computor "3 * X^7 - 5 * X^4 + 8 * X^2 - 11 * X^1 - 4 * X^0 = 3 * X^7 - 5 * X^4 + 8 * X^2 - 2 * X^1 - 4 * X^0"'

    # ========================================
    # Zero X^1 coefficient on one side
    # ========================================

    './computor "8 * X^5 + 4 * X^3 + 0 * X^1 + 7 * X^0 = 8 * X^5 + 4 * X^3 + 5 * X^1 + 2 * X^0"'
    './computor "6 * X^6 - 3 * X^4 + 0 * X^2 - 9 * X^1 + 4 * X^0 = 6 * X^6 - 3 * X^4 + 0 * X^2 + 3 * X^1 - 8 * X^0"'

    # ========================================
    # Very large coefficients
    # ========================================

    './computor "1000 * X^8 - 500 * X^6 + 250 * X^4 + 750 * X^2 + 1234 * X^1 - 987 * X^0 = 1000 * X^8 - 500 * X^6 + 250 * X^4 + 750 * X^2 + 234 * X^1 - 487 * X^0"'
    './computor "-999 * X^7 + 888 * X^5 - 777 * X^3 + 666 * X^1 + 555 * X^0 = -999 * X^7 + 888 * X^5 - 777 * X^3 - 444 * X^1 - 222 * X^0"'

    # ========================================
    # Sparse high-degree polynomials
    # ========================================

    './computor "12 * X^10 - 7 * X^7 + 4 * X^3 + 15 * X^1 - 6 * X^0 = 12 * X^10 - 7 * X^7 + 4 * X^3 + 5 * X^1 + 9 * X^0"'
    './computor "3 * X^12 + 8 * X^9 - 5 * X^4 - 11 * X^1 + 7 * X^0 = 3 * X^12 + 8 * X^9 - 5 * X^4 + 6 * X^1 - 3 * X^0"'

    # ========================================
    # Terms in unusual order
    # ========================================

    './computor "4 * X^1 + 9 * X^4 + 2 * X^0 + 7 * X^3 = 1 * X^0 + 9 * X^4 + 6 * X^1 + 7 * X^3"'
    './computor "8 * X^2 - 3 * X^6 + 5 * X^1 + 9 * X^5 - 4 * X^0 = 8 * X^2 - 3 * X^6 + 9 * X^5 - 2 * X^1 - 4 * X^0"'

    # ========================================
    # Fractional decimal coefficients
    # ========================================

    './computor "1.25 * X^5 - 2.75 * X^3 + 4.125 * X^2 + 6.625 * X^1 - 3.5 * X^0 = 1.25 * X^5 - 2.75 * X^3 + 4.125 * X^2 + 1.625 * X^1 + 2.5 * X^0"'
    './computor "0.125 * X^8 + 0.75 * X^6 - 1.625 * X^4 + 2.5 * X^1 + 0.875 * X^0 = 0.125 * X^8 + 0.75 * X^6 - 1.625 * X^4 - 3.5 * X^1 - 1.125 * X^0"'
)


: > computor_test_results.txt

for cmd in "${INPUTS[@]}"; do
    echo "========================================" | tee -a computor_test_results.txt
    echo "$cmd" | tee -a computor_test_results.txt
    echo "========================================" | tee -a computor_test_results.txt
    eval "$cmd" 2>&1 | tee -a computor_test_results.txt
    echo | tee -a computor_test_results.txt
done

echo "Results saved to computor_test_results.txt"