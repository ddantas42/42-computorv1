#!/bin/bash

INPUTS=(
    # ========================================
    # Zero terms explicitly present
    # ========================================

    './computor "8 * X^0 - 6 * X^1 + 0 * X^2 - 5.6 * X^3 = 3 * X^0"'
    './computor "0 * X^3 + 4 * X^2 + 0 * X^1 + 8 * X^0 = 2 * X^2"'
    './computor "5 * X^2 + 0 * X^1 + 5 * X^0 = 0 * X^2 + 0 * X^1 + 0 * X^0"'
    './computor "0 * X^2 + 7 * X^1 + 3 * X^0 = 0 * X^1 + 3 * X^0"'
    './computor "9 * X^2 + 0 * X^1 + 0 * X^0 = 4 * X^2 + 0 * X^1 + 0 * X^0"'

    # ========================================
    # X^1 terms cancel completely
    # ========================================

    './computor "5 * X^2 + 7 * X^1 + 3 * X^0 = 2 * X^2 + 7 * X^1 + 1 * X^0"'
    './computor "8 * X^2 - 4 * X^1 + 6 * X^0 = 3 * X^2 - 4 * X^1 + 2 * X^0"'
    './computor "10 * X^2 + 12 * X^1 + 5 * X^0 = 10 * X^2 + 12 * X^1 + 9 * X^0"'
    './computor "3 * X^3 + 5 * X^2 - 9 * X^1 + 4 * X^0 = 1 * X^3 + 2 * X^2 - 9 * X^1 + 8 * X^0"'

    # ========================================
    # X^2 terms cancel completely
    # ========================================

    './computor "5 * X^2 + 4 * X^1 + 3 * X^0 = 5 * X^2 + 2 * X^1 + 1 * X^0"'
    './computor "8 * X^2 - 6 * X^1 + 2 * X^0 = 8 * X^2 + 4 * X^1 + 10 * X^0"'
    './computor "12 * X^2 + 5 * X^1 + 7 * X^0 = 12 * X^2 + 5 * X^1 + 7 * X^0"'

    # ========================================
    # X^0 terms cancel completely
    # ========================================

    './computor "4 * X^2 + 3 * X^1 + 8 * X^0 = 2 * X^2 + 1 * X^1 + 8 * X^0"'
    './computor "7 * X^2 - 5 * X^1 - 3 * X^0 = 3 * X^2 - 2 * X^1 - 3 * X^0"'

    # ========================================
    # Multiple terms cancel simultaneously
    # ========================================

    './computor "5 * X^2 + 7 * X^1 + 9 * X^0 = 5 * X^2 + 7 * X^1 + 4 * X^0"'
    './computor "8 * X^2 + 6 * X^1 + 3 * X^0 = 8 * X^2 + 2 * X^1 + 3 * X^0"'
    './computor "4 * X^3 + 9 * X^2 + 5 * X^1 + 7 * X^0 = 4 * X^3 + 9 * X^2 + 5 * X^1 + 7 * X^0"'

    # ========================================
    # Cancellation changes the polynomial degree
    # ========================================

    './computor "5 * X^3 + 4 * X^2 + 3 * X^1 + 2 * X^0 = 5 * X^3 + 1 * X^2 + 3 * X^1 + 2 * X^0"'
    './computor "7 * X^4 + 2 * X^3 + 6 * X^2 + 5 * X^1 + 1 * X^0 = 7 * X^4 + 2 * X^3 + 1 * X^2 + 5 * X^1 + 1 * X^0"'
    './computor "9 * X^3 + 8 * X^2 + 7 * X^1 + 6 * X^0 = 9 * X^3 + 8 * X^2 + 2 * X^1 + 6 * X^0"'

    # ========================================
    # Everything cancels -> 0 = 0
    # ========================================

    './computor "5 * X^2 + 4 * X^1 + 3 * X^0 = 5 * X^2 + 4 * X^1 + 3 * X^0"'
    './computor "8 * X^3 - 6 * X^2 + 4 * X^1 - 2 * X^0 = 8 * X^3 - 6 * X^2 + 4 * X^1 - 2 * X^0"'

    # ========================================
    # Constant-only equations
    # ========================================

    './computor "5 * X^0 = 3 * X^0"'
    './computor "7 * X^0 = 7 * X^0"'
    './computor "0 * X^0 = 0 * X^0"'
    './computor "8 * X^0 = 0 * X^0"'

    # ========================================
    # Linear equations after cancellation
    # ========================================

    './computor "5 * X^2 + 4 * X^1 + 3 * X^0 = 5 * X^2 + 1 * X^1 + 3 * X^0"'
    './computor "7 * X^2 - 6 * X^1 + 2 * X^0 = 7 * X^2 + 4 * X^1 + 2 * X^0"'
    './computor "3 * X^3 + 8 * X^1 + 5 * X^0 = 3 * X^3 + 2 * X^1 + 5 * X^0"'

    # ========================================
    # Quadratics with b = 0
    # ========================================

    './computor "3 * X^2 + 0 * X^1 + 2 * X^0 = 0 * X^1"'
    './computor "5 * X^2 + 7 * X^0 = 0 * X^1 + 2 * X^0"'
    './computor "4 * X^2 + 9 * X^0 = 0 * X^1 + 1 * X^0"'

    # ========================================
    # Quadratics with c = 0
    # ========================================

    './computor "5 * X^2 + 3 * X^1 + 0 * X^0 = 0 * X^0"'
    './computor "2 * X^2 - 7 * X^1 + 0 * X^0 = 0 * X^0"'
    './computor "9 * X^2 + 4 * X^1 + 0 * X^0 = 3 * X^1 + 0 * X^0"'

    # ========================================
    # Negative coefficients
    # ========================================

    './computor "-5 * X^2 + 7 * X^1 - 3 * X^0 = -2 * X^2 + 4 * X^1 - 1 * X^0"'
    './computor "6 * X^2 - 9 * X^1 - 4 * X^0 = 2 * X^2 - 3 * X^1 - 8 * X^0"'
    './computor "-3 * X^2 - 5 * X^1 + 7 * X^0 = -3 * X^2 + 2 * X^1 + 1 * X^0"'

    # ========================================
    # Decimal coefficients
    # ========================================

    './computor "5.5 * X^2 + 2.5 * X^1 + 1.5 * X^0 = 2.5 * X^2 + 2.5 * X^1 + 0.5 * X^0"'
    './computor "0.5 * X^2 + 0.25 * X^1 + 0.75 * X^0 = 0.25 * X^2 + 0.25 * X^1 + 0.25 * X^0"'
    './computor "8 * X^0 - 6 * X^1 + 0 * X^2 - 5.6 * X^3 = 3 * X^0"'

    # ========================================
    # Degree > 2 after reduction
    # ========================================

    './computor "5 * X^3 + 4 * X^2 + 2 * X^1 + 1 * X^0 = 2 * X^2 + 1 * X^1"'
    './computor "4 * X^4 + 3 * X^3 + 2 * X^2 + 1 * X^0 = 1 * X^3 + 1 * X^0"'

    # ========================================
    # Higher degree completely cancels
    # ========================================

    './computor "5 * X^4 + 3 * X^3 + 2 * X^2 = 5 * X^4 + 3 * X^3 + 2 * X^2"'
    './computor "7 * X^3 + 4 * X^2 + 9 * X^1 = 7 * X^3 + 4 * X^2 + 9 * X^1"'
)

: > computor_test_results.txt

for cmd in "${INPUTS[@]}"; do
    echo "========================================" | tee -a computor_test_results.txt
    echo "$cmd" | tee -a computor_test_results.txt
    echo "========================================" | tee -a computor_test_results.txt
    eval "$cmd" 2>&1 | tee -a computor_test_results.txt
    echo | tee -a computor_test_results.txt
done

echo "Results saved to computor_test_results.txt"